export function getSmartEgyptianReply(userText: string): string {
  const text = userText.trim();
  const lower = text.toLowerCase();

  for (const group of EGYPTIAN_FRIEND_RESPONSES) {
    if (group.keywords.some(k => lower.includes(k))) {
      // Pick a reply that hasn't been used recently
      const available = group.replies.filter(r => !recentRepliesRing.has(r));
      const pool = available.length > 0 ? available : group.replies;
      const chosen = pool[Math.floor(Math.random() * pool.length)];

      recentRepliesRing.add(chosen);
      if (recentRepliesRing.size > 20) {
        const oldest = recentRepliesRing.values().next().value;
        if (oldest) recentRepliesRing.delete(oldest);
      }
      return chosen;
    }
  }

  // Varied natural Egyptian conversational reflections (never repetitive)
  const conversationalStarters = [
    `يا سيدي على كلامك الحلو! بجد نورتني.. كمل احكيلي أنا معاك وسامعة كل تفصيلة، قولي بقى إيه اللي في بالك؟`,
    `والله كلامك دخل قلبي على طول! قولي يا غالي ولا يهمك، أنا معاك ومركزة أوي في كل كلمة، احكيلي أكتر.`,
    `يا هلا بيك وبكلامك الجميل! أنا مبسوطة أوي بالدردشة دي معاك.. كمل أنا سامعاك ومشغولة بيك، طمني عنك وعن يومك.`,
    `الله على روقانك وجمال حكاياتك! معاك خطوة بخطوة ومش مستعجلة على أي حاجة، فضفضلي وقولي رأيك إيه؟`
  ];

  const availableGenerals = conversationalStarters.filter(r => !recentRepliesRing.has(r));
  const pool = availableGenerals.length > 0 ? availableGenerals : conversationalStarters;
  const chosenGeneral = pool[Math.floor(Math.random() * pool.length)];

  recentRepliesRing.add(chosenGeneral);
  if (recentRepliesRing.size > 20) {
    const oldest = recentRepliesRing.values().next().value;
    if (oldest) recentRepliesRing.delete(oldest);
  }

  return chosenGeneral;
}

